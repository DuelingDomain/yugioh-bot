export interface AcceptanceCase { mode: DuelMode; format: DuelFormat; engine?: DuelEngineChoice }
export const ACCEPTANCE_CASES: AcceptanceCase[] = (["normal", "domain"] as const).flatMap(mode => [
  { mode, format: "1v1", engine: "legacy" }, { mode, format: "1v1", engine: "pinned" },
  { mode, format: "tag" }, { mode, format: "ffa3" }, { mode, format: "ffa4" },
]);

/** Fixed inputs, not a journal generated by today's engine. Gapped IDs test ordered count semantics. */
export function fixedJournal(answers: DuelAnswer[], seat = 0): ReplayJournalEntry[] {
  return answers.map((answer, revision) => ({ storedSeq: 10 + revision * 7, seat,
    command: { revision, promptId: `p${Math.max(0, revision - 1)}-${revision + 1}`, answer } }));
}

/** Cup of Ace resolves Tails with this seed; multi FFA asks who receives the draw. */
export function cupJournal(format: DuelFormat): ReplayJournalEntry[] {
  return fixedJournal([{ choice: "activate:0" },
    ...(format.startsWith("ffa") ? [{ choice: "opt:0" }] : []), { selected: ["place:0"] },
    ...(format === "tag" ? [{ choice: "opt:0" }] : [])]);
}
