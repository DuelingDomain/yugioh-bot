export function acceptanceSource(entry: AcceptanceCase) {
  const count = seatCountFor(entry.format), current = getCurrentEngineResources(DATA, entry);
  const source: ReplaySource = {
    session: { id: 1, slug: "acceptance-source", kind: "play", guildId: "acceptance-guild", name: "Source game 2",
      organizerPlayerId: 201, mode: entry.mode, format: entry.format, masterRule: 5, status: "interrupted",
      settings: { ...defaultDuelSettings(entry.mode), visibility: "private", shuffleDeck: false,
        validateDeck: false, stopAtEveryWindow: true, turnSeconds: 60 },
      // A game-2 order is already swapped. The owner is not a source player.
      seats: Array.from({ length: count }, (_, seat) => ({ seat, playerId: 201 + (seat + 1) % count,
        displayName: `Source ${seat}`, ready: true, isBot: false })),
      createdAt: "2026-10-10T00:00:00Z", endedAt: null, archivedAt: null,
      winnerPlayerId: null, winnerSeat: null, resultReason: "Saved host interruption" },
    decks: Array.from({ length: count }, (_, seat) => ({ main: [...OPENING_HAND, ...Array(35).fill(MAGICIAN)],
      extra: [SPIDER], side: [seat % 2 ? MASTER : POKI], ...(entry.mode === "domain" ? { deckMaster: MASTER } : {}) })),
    seed: ["1", "2", "3", "4"], bundleVersion: current.bundleVersion, engineIdentity: current.identity,
    setup: { engine: entry.engine, firstTurnDraw: false, scriptErrorMode: "strict" },
    commands: cupJournal(entry.format),
  };
  const resources = { dataDirectory: DATA,
    // The runner takes the manifest version, then adds the overlay hash itself.
    bundleVersion: JSON.parse(readFileSync(join(DATA, "manifest.json"), "utf8")).bundleVersion as string,
    engineIdentity: current.identity, multiScriptsDirectory: current.multiScriptsDirectory };
  return { source, resources };
}

/** This Lua is original source setup. Fork launch must copy it without adding any phase scripts. */
export function rotationSource(mode: DuelMode) {
  const fixture = acceptanceSource({ mode, format: "ffa4" });
  const masters = mode === "domain" ? { deckMaster: MASTER } : {};
  const { options } = compileBoard({ mode, format: "ffa4",
    p0: { hand: [31036355], monsters: [14015067, MAGICIAN], ...masters },
    p1: { monsters: [70781052, MAGICIAN], ...masters },
    p2: { monsters: [89631139, MAGICIAN], ...masters },
    p3: { monsters: [91152256, MAGICIAN], ...masters },
  }, DATA);
  fixture.source.decks = options.decks;
  fixture.source.session.settings = { ...fixture.source.session.settings, ...options.settings };
  fixture.source.setup!.startupScripts = options.startupScripts!.map(script => script.content);
  fixture.source.commands = fixedJournal([{ choice: "activate:0" }, { selected: ["place:0"] },
    { selected: ["card:0"] }, { selected: ["card:0"] }]);
  fixture.source.commands[3]!.seat = 1;
  fixture.source.commands.push({ storedSeq: 40, seat: 1,
    command: { revision: 4, promptId: "eliminate:0", answer: {} } });
  return fixture;
}
