import { loadCardPasscodeRemaps } from "@yugidraft/shared/db";
import { existsSync, readFileSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Database from "better-sqlite3";
import { canonicalCardCode, mapDeckCodes, type DuelDeck } from "@yugidraft/shared/duels";
import { createCardCatalogService, createDraftService, type CardLookupBudget } from "@yugidraft/shared/services";
import { DeckLegalityError, type InspectDeckOptions } from "./deck-legality.js";
import { isPlayable, normalizeArtworkName, type EngineRow } from "./engine-card-identity.js";

type FetchLike = (
  input: string | URL | globalThis.Request,
  init?: globalThis.RequestInit,
) => Promise<Pick<Response, "ok" | "json">>;

type NormalizeImportedDeckOptions = {
  fetch?: FetchLike;
  keepUnresolved?: boolean;
  lookupBudget?: CardLookupBudget;
  cacheOnly?: boolean;
  lookupLimitedCodes?: Set<number>;
};

type EngineIndex = {
  mtime: number;
  byId: Map<number, EngineRow>;
  byName: Map<string, EngineRow[]>;
};

const engineIndexes = new Map<string, EngineIndex>();

// Dueling Book exports alt_passcode instead of serial_number for some artworks:
// https://static.duelingbook.com/utils.js (exportDeckYDK / exportDeckYDKE).
// Generated by scripts/update-duelingbook-passcodes.ts against the prepared engine database.
const packageDirectory = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const simulatorArtworkIds = new Map<number, number>(Object.entries(
  JSON.parse(readFileSync(join(packageDirectory, "duelingbook-alt-passcodes.json"), "utf8")) as Record<string, number>,
).map(([alt, code]) => [Number(alt), code]));
const simulatorArtworkNames = new Map<number, string>(Object.entries(
  JSON.parse(readFileSync(join(packageDirectory, "duelingbook-alt-passcode-names.json"), "utf8")) as Record<string, string>,
).map(([code, name]) => [Number(code), name]));

function fail(message: string): never {
  throw new DeckLegalityError(message);
}

function normalizeName(name: string): string {
  return name.trim().toLowerCase();
}

function loadEngineIndex(dataDirectory: string): EngineIndex {
  const root = resolve(dataDirectory);
  const cdbPath = join(root, "cards.cdb");
  if (!existsSync(cdbPath)) fail(`Cannot read engine card database at ${cdbPath}`);
  const mtime = statSync(cdbPath).mtimeMs;
  const cached = engineIndexes.get(root);
  if (cached && cached.mtime === mtime) return cached;

  const cdb = new Database(cdbPath, { readonly: true, fileMustExist: true });
  const byId = new Map<number, EngineRow>();
  const byName = new Map<string, EngineRow[]>();
  try {
    const rows = cdb
      .prepare<[], EngineRow>(
        "SELECT datas.id, datas.ot, datas.alias, datas.type, texts.name FROM datas LEFT JOIN texts USING (id)",
      )
      .all();
    for (const row of rows) {
      const entry: EngineRow = {
        id: Number(row.id),
        ot: Number(row.ot),
        alias: Number(row.alias),
        type: Number(row.type),
        name: row.name ?? "",
      };
      byId.set(entry.id, entry);
      const key = normalizeName(entry.name);
      if (!key) continue;
      const group = byName.get(key);
      if (group) group.push(entry);
      else byName.set(key, [entry]);
    }
  } finally {
    cdb.close();
  }

  const index: EngineIndex = { mtime, byId, byName };
  engineIndexes.set(root, index);
  return index;
}

function requireCardId(value: unknown): number {
  if (typeof value !== "number" || !Number.isSafeInteger(value) || value <= 0) {
    fail(`Unknown card ${String(value)}`);
  }
  return value;
}

function requireCardIds(value: unknown): number[] {
  if (!Array.isArray(value)) fail("Deck must include main, extra, and side arrays");
  const ids: number[] = [];
  for (const entry of value) {
    ids.push(requireCardId(entry));
  }
  return ids;
}

function canonicalForName(index: EngineIndex, name: string, sourceId: number): number {
  const matches = index.byName.get(normalizeName(name)) ?? [];
  const playable = matches.filter(isPlayable);
  const canonical = playable.filter((card) => card.alias === 0);
  if (canonical.length === 1) return canonical[0].id;
  if (canonical.length > 1) fail(`Ambiguous card ${sourceId} (${name})`);

  const aliasTargets = new Set<number>();
  for (const card of playable) {
    if (card.alias !== 0) aliasTargets.add(card.alias);
  }
  if (aliasTargets.size === 1) {
    const [targetId] = aliasTargets;
    const target = targetId === undefined ? undefined : index.byId.get(targetId);
    if (target && isPlayable(target)) return target.id;
  }
  if (aliasTargets.size > 1) fail(`Ambiguous card ${sourceId} (${name})`);
  fail(`Unknown card ${sourceId} (${name})`);
}

/** Resolve verified simulator ids over missing/unplayable engine rows; use catalog names only for missing ids. */
async function resolveMissingIds(
  index: EngineIndex,
  allIds: number[],
  db: Database.Database,
  options: NormalizeImportedDeckOptions,
): Promise<Map<number, number>> {
  const missing: number[] = [];
  const seenMissing = new Set<number>();
  const resolved = new Map<number, number>();
  for (const id of allIds) {
    const source = index.byId.get(id);
    if ((source && isPlayable(source)) || seenMissing.has(id)) continue;
    seenMissing.add(id);
    const artwork = simulatorArtworkIds.get(id);
    const original = artwork === undefined ? undefined : index.byId.get(artwork);
    const name = artwork === undefined ? undefined : simulatorArtworkNames.get(artwork);
    if (original && name && original.alias === 0 && isPlayable(original) && normalizeArtworkName(original.name) === normalizeArtworkName(name)) {
      resolved.set(id, original.id);
      continue;
    }
    if (!source) missing.push(id);
  }

  if (missing.length > 0) {
    const catalog = createCardCatalogService(db, { fetch: options.fetch });
    const cached = catalog.findByIds(missing);
    const nameByInputId = new Map<number, string>();
    for (const card of cached) nameByInputId.set(card.ygoprodeckId, card.name);
    for (const id of missing) {
      if (nameByInputId.has(id)) continue;
      // An earlier response or a concurrent request can fill this cache during the loop.
      const newlyCached = catalog.findByIds([id])[0];
      if (newlyCached) { nameByInputId.set(id, newlyCached.name); continue; }
      if (options.cacheOnly) continue;
      if (options.lookupBudget && options.lookupBudget.remaining <= 0) {
        options.lookupBudget.lookupLimited = true;
        options.lookupLimitedCodes?.add(id);
        continue;
      }
      const card = await catalog.syncCardById(id, { lookupBudget: options.lookupBudget,
        ...(options.lookupBudget ? { enrichArtwork: false } : {}) });
      if (card) nameByInputId.set(id, card.name);
    }
    for (const id of missing) {
      const name = nameByInputId.get(id);
      if (!name) {
        if (options.keepUnresolved) continue;
        fail(`Unknown card ${id}`);
      }
      try {
        resolved.set(id, canonicalForName(index, name, id));
      } catch (error) {
        if (options.keepUnresolved && error instanceof DeckLegalityError) continue;
        throw error;
      }
    }
  }
  return resolved;
}

/** Canonical identity for card-count checks, including artwork ids stored before normalization. */
export function canonicalEngineCardCode(code: number, dataDirectory: string): number {
  return canonicalCardCode(loadCardPasscodeRemaps(dataDirectory).get(code) ?? code, loadEngineIndex(dataDirectory).byId);
}

export async function normalizeImportedDeck(
  deck: DuelDeck,
  dataDirectory: string,
  db: Database.Database,
  options: NormalizeImportedDeckOptions = {},
): Promise<DuelDeck> {
  if (deck == null || typeof deck !== "object") fail("Deck must include main, extra, and side arrays");
  const graduated = loadCardPasscodeRemaps(dataDirectory);
  const remapGraduated = (id: number) => graduated.get(id) ?? id;
  const main = requireCardIds(deck.main).map(remapGraduated);
  const extra = requireCardIds(deck.extra).map(remapGraduated);
  const side = requireCardIds(deck.side).map(remapGraduated);
  const deckMaster = deck.deckMaster === undefined ? undefined : remapGraduated(requireCardId(deck.deckMaster));

  const index = loadEngineIndex(dataDirectory);
  const allIds = deckMaster === undefined ? [...main, ...extra, ...side] : [...main, ...extra, ...side, deckMaster];
  const resolved = await resolveMissingIds(index, allIds, db, options);

  const remap = (id: number): number => resolved.get(id) ?? id;
  return mapDeckCodes({ main, extra, side, ...(deckMaster !== undefined ? { deckMaster } : {}) }, remap);
}

/** Canonical engine identity for pool and count checks; unresolved ids map to null. */
export async function normalizeCardCodes(
  codes: number[],
  dataDirectory: string,
  db: Database.Database,
  options: Omit<NormalizeImportedDeckOptions, "keepUnresolved"> & {
    preserveArtwork?: boolean; canonicalCodes?: Map<number, number | null>;
  } = {},
): Promise<Map<number, number | null>> {
  const inputIds = requireCardIds(codes);
  const graduated = loadCardPasscodeRemaps(dataDirectory);
  const ids = inputIds.map(id => graduated.get(id) ?? id);
  const index = loadEngineIndex(dataDirectory);
  const limited = new Set<number>();
  const resolved = await resolveMissingIds(index, ids, db, { ...options, keepUnresolved: true, lookupLimitedCodes: limited });
  const result = new Map<number, number | null>();
  for (const inputId of inputIds) {
    const id = graduated.get(inputId) ?? inputId;
    const known = resolved.get(id) ?? (index.byId.has(id) ? id : undefined);
    const canonical = known === undefined ? null : canonicalCardCode(known, index.byId);
    result.set(inputId, known === undefined ? null : options.preserveArtwork ? known : canonical);
    options.canonicalCodes?.set(inputId, canonical);
    if (limited.has(id)) options.lookupLimitedCodes?.add(inputId);
  }
  return result;
}

/** Trusted draft pool and forced allowances, using the same engine artwork identity as deck checks. */
export async function loadDraftDeckPool(input: {
  draftId: number;
  playerId: number;
  guildId: string;
  dataDirectory: string;
  db: Database.Database;
}): Promise<NonNullable<InspectDeckOptions["draftPool"]>> {
  const { db, draftId, playerId, guildId, dataDirectory } = input;
  const participant = db.prepare(`
    select d.id from drafts d
    join draft_players dp on dp.draft_id = d.id
    join players p on p.id = dp.player_id and p.guild_id = d.guild_id
    where d.id = ? and d.guild_id = ? and d.status = 'completed' and p.id = ?
  `).get(draftId, guildId, playerId);
  if (!participant) fail("Draft pool is not available for this player");
  const picks = createDraftService(db).pool(draftId, playerId);
  const codes = await normalizeCardCodes([...new Set(picks.map((pick) => pick.catalogCardId))], dataDirectory, db);
  const counts = new Map<number, number>();
  const forcedCopies = new Map<number, number>();
  for (const pick of picks) {
    const code = codes.get(pick.catalogCardId);
    if (typeof code !== "number") continue;
    counts.set(code, (counts.get(code) ?? 0) + 1);
    if (pick.forced) forcedCopies.set(code, (forcedCopies.get(code) ?? 0) + 1);
  }
  return { counts, forcedCopies };
}
