/**
 * The float32 reference for the WebGPU output check (packages/vision/src/gpu-check.ts), computed on the CPU
 * with the pinned float32 embedder graph. It runs the production embedImages path on checkImage(), so the
 * input is normalised exactly like a crop in the browser.
 *
 *   VISION_DATA_DIR=<dir with models/> npx tsx scripts/vision/gpu-check-reference.ts           verify the stored reference
 *   VISION_DATA_DIR=<dir with models/> npx tsx scripts/vision/gpu-check-reference.ts --write   regenerate it
 *
 * Needs dinov2-small-duel.fp32.onnx (checked against its pinned sha256); the fp16 graph, if present, is run on
 * the CPU too, as a sanity check that a correct fp16 run passes (cosine about 0.999+). Copy both from the VM:
 * scp dueling-system:/opt/yugioh-bot/data/vision/models/dinov2-small-duel.fp{16,32}.onnx <dir>/models/
 */
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { basename, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as ort from 'onnxruntime-node';
import { embedImages, type SessionLike, type TensorCtor } from '../../packages/vision/src/embed';
import { CHECK_SEED, checkImage } from '../../packages/vision/src/gpu-check';
import { dinov2SmallDuelCheck as stored } from '../../packages/vision/src/gpu-check-reference';
import { duelLensModel as spec } from '../../packages/vision/src/models';

const models = join(resolve(process.env.VISION_DATA_DIR ?? 'data/vision'), 'models');
const fp32 = spec.webgpu!.fp32!, fp16 = spec.webgpu!;
const cosine = (a: ArrayLike<number>, b: ArrayLike<number>) => { let d = 0; for (let i = 0; i < a.length; i++) d += a[i] * b[i]; return d; }; // both L2-normalised

async function embed(file: string, image = checkImage(spec.inputSize)): Promise<Float32Array> {
  const session = await ort.InferenceSession.create(join(models, basename(file)), { executionProviders: ['cpu'] });
  try { return (await embedImages(session as unknown as SessionLike, ort.Tensor as unknown as TensorCtor, spec, [image]))[0]; }
  finally { await session.release(); }
}

const bytes = await readFile(join(models, basename(fp32.url)));
const sha = createHash('sha256').update(bytes).digest('hex');
if (sha !== fp32.sha256) throw new Error(`${basename(fp32.url)} is ${sha}, the spec pins ${fp32.sha256}`);
const reference = await embed(fp32.url);
const norm = Math.sqrt(cosine(reference, reference));
console.log(`fp32 CPU reference: ${reference.length} values, norm ${norm.toFixed(6)}, all finite: ${reference.every(Number.isFinite)}`);

const fresh = stored.fp32Sha256 === sha && stored.values.length === reference.length ? cosine(stored.values, reference) : NaN;
console.log(`stored reference vs fresh fp32 CPU run: cosine ${fresh.toFixed(7)}${stored.fp32Sha256 === sha ? '' : ' (stored one is for another graph)'}`);

try {
  const half = await embed(fp16.url);
  console.log(`fp16 graph on CPU vs fp32 reference: cosine ${cosine(half, reference).toFixed(6)} (minCosine ${spec.gpuCheck?.minCosine})`);
} catch (error) { console.log(`fp16 graph not run: ${error instanceof Error ? error.message : error}`); }

// What the threshold has to tell apart: the same kind of picture with another seed, and pictures this embedder maps to one
// common vector (any stripes, gradients or noise). A graph that ignored its input would give the last kind.
const blank = (fill: (x: number, y: number) => number) => { const size = spec.inputSize, data = new Uint8ClampedArray(size * size * 4); for (let i = 0; i < size * size; i++) data.set([fill(i % size, Math.floor(i / size)), 128, 128, 255], i * 4); return { data, width: size, height: size }; };
for (const seed of [CHECK_SEED + 1, CHECK_SEED + 2, CHECK_SEED + 3]) console.log(`other ripples (seed ${seed}) vs reference: cosine ${cosine(await embed(fp32.url, checkImage(spec.inputSize, seed)), reference).toFixed(4)}`);
console.log(`stripes picture vs reference: cosine ${cosine(await embed(fp32.url, blank(x => (x >> 3 & 1) * 255)), reference).toFixed(4)}`);
console.log(`flat grey picture vs reference: cosine ${cosine(await embed(fp32.url, blank(() => 128)), reference).toFixed(4)}`);

if (process.argv.includes('--write')) {
  const values = [...reference].map(v => Number(v.toPrecision(7)));
  const file = fileURLToPath(new URL('../../packages/vision/src/gpu-check-reference.ts', import.meta.url));
  await writeFile(file, `// Generated by scripts/vision/gpu-check-reference.ts from ${basename(fp32.url)}; do not edit by hand.
// That graph's L2-normalised output, run on the CPU, for checkImage(${spec.inputSize}) (gpu-check.ts).
export const dinov2SmallDuelCheck = { fp32Sha256: '${sha}', values: [${values.join(',')}] };
`);
  console.log(`wrote ${file}`);
} else if (!(fresh >= 0.9999)) {
  console.error('The stored reference does not match this graph: run again with --write.');
  process.exitCode = 1;
}
